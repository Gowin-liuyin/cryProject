static uint8_t substitute_byte(uint8_t secret_index)
{
#if MEM_LUT_LEAK_ENABLED
    /* 故意保留秘密地址，作为访存定位工具的人工阳性。 */
    return substitution_table[secret_index];
#else
    uint32_t selected_value = 0U;
    for (uint32_t table_index = 0U; table_index < MEM_LUT_TABLE_ENTRIES; table_index++) {
        uint32_t index_difference = (uint32_t)secret_index ^ table_index;
        uint32_t match_mask = (index_difference - 1U) >> 8U;
        selected_value |= (uint32_t)substitution_table[table_index] & match_mask;
    }
    return (uint8_t)selected_value;
#endif
}

int mem_lut_apply(const uint8_t *secret_input,
    size_t secret_input_bytes,
    uint8_t *output,
    size_t output_capacity_bytes)
{
    if (secret_input == NULL || output == NULL || secret_input_bytes != MEM_LUT_INPUT_BYTES ||
        output_capacity_bytes < MEM_LUT_INPUT_BYTES) {
        return -1;
    }
    /* 先完成变换再写输出，使原地和部分重叠调用保持相同语义。 */
    uint8_t transformed_input[MEM_LUT_INPUT_BYTES];
    for (size_t input_index = 0U; input_index < MEM_LUT_INPUT_BYTES; input_index++) {
        transformed_input[input_index] = substitute_byte(secret_input[input_index]);
    }
    for (size_t output_index = 0U; output_index < MEM_LUT_INPUT_BYTES; output_index++) {
        output[output_index] = transformed_input[output_index];
    }
    return 0;
}
